import { randomUUID } from 'node:crypto';
import { and, asc, eq, gte, isNull, lte, lt } from 'drizzle-orm';
import { db } from '@/db/client.js';
import { config } from '@/config.js';
import { conversationEvents, conversations, episodes, messages } from '@/db/schema/index.js';
import { appendConversationEvent } from '@/modules/analytics/log.js';

/**
 * Builds the `episodes` analytics projection from the `conversation_events` log.
 * Idempotent and incremental: only episodes that are *finalized* (closed longer
 * than the reopen window, so a within-window reopen can no longer change them)
 * and not already materialized are written, once. The table can always be
 * dropped and fully regenerated by running this.
 */

/**
 * Seed `currentEpisodeId` + opening (and closing) events for conversations that
 * predate event logging, so they participate in analytics. Idempotent — only
 * touches conversations still missing a `currentEpisodeId`. Historical handoff/
 * escalation detail is unavailable, so those episodes derive what they can from
 * messages (first response, agent involvement); see `materializeEpisode`.
 */
export function backfillEpisodeIds(): number {
  const legacy = db
    .select()
    .from(conversations)
    .where(isNull(conversations.currentEpisodeId))
    .all();

  for (const c of legacy) {
    const episodeId = randomUUID();
    db.update(conversations)
      .set({ currentEpisodeId: episodeId })
      .where(eq(conversations.id, c.id))
      .run();
    appendConversationEvent({
      conversationId: c.id,
      episodeId,
      type: 'episode_opened',
      at: c.createdAt,
    });
    if (c.status === 'closed') {
      appendConversationEvent({
        conversationId: c.id,
        episodeId,
        type: 'closed',
        at: c.lastMessageAt,
      });
    }
  }
  return legacy.length;
}

/** Materialize finalized episodes into `episodes`. Returns how many were added. */
export function refreshEpisodes(now: Date = new Date()): number {
  const cutoff = new Date(now.getTime() - config.episodeReopenWindowMs);

  // Already-materialized ids (skip — they're immutable once written).
  const done = new Set(
    db
      .select({ id: episodes.id })
      .from(episodes)
      .all()
      .map((r) => r.id),
  );

  // Candidates: episodes with a close older than the reopen window.
  const candidates = db
    .selectDistinct({ episodeId: conversationEvents.episodeId })
    .from(conversationEvents)
    .where(and(eq(conversationEvents.type, 'closed'), lt(conversationEvents.createdAt, cutoff)))
    .all()
    .map((r) => r.episodeId)
    .filter((id) => !done.has(id));

  let added = 0;
  for (const id of candidates) {
    if (materializeEpisode(id, cutoff)) added += 1;
  }
  return added;
}

/** Build one episode row from its events + messages. Skips if not actually
 *  finalized (its latest event isn't a window-old close). Returns true if a row
 *  was inserted. */
function materializeEpisode(episodeId: string, cutoff: Date): boolean {
  const evs = db
    .select()
    .from(conversationEvents)
    .where(eq(conversationEvents.episodeId, episodeId))
    .orderBy(asc(conversationEvents.createdAt))
    .all();
  if (evs.length === 0) return false;

  const last = evs[evs.length - 1];
  // Finalized only if the latest event is a close that's past the window (a
  // later reopen would make the last event non-closed).
  if (last.type !== 'closed' || last.createdAt.getTime() >= cutoff.getTime()) return false;

  const first = evs[0];
  const conversationId = last.conversationId;
  const openedAt = first.createdAt;
  const closedAt = last.createdAt;

  // First human reply within the episode window (works for backfilled episodes
  // too, since it reads messages, not events).
  const firstAgent = db
    .select({ at: messages.createdAt, agentId: messages.senderAgentId })
    .from(messages)
    .where(
      and(
        eq(messages.conversationId, conversationId),
        eq(messages.author, 'agent'),
        gte(messages.createdAt, openedAt),
        lte(messages.createdAt, closedAt),
      ),
    )
    .orderBy(asc(messages.createdAt))
    .get();

  const escalated = evs.some((e) => e.type === 'escalated');
  const handedOff = evs.some((e) => e.type === 'taken_over') || firstAgent != null;

  db.insert(episodes)
    .values({
      id: episodeId,
      conversationId,
      openedAt,
      closedAt,
      openedVia: first.type === 'reopened' ? 'reopen' : 'new',
      firstResponseAt: firstAgent?.at ?? null,
      firstResponseAgentId: firstAgent?.agentId ?? null,
      closedByAgentId: last.actorAgentId,
      handedOff,
      aiDeflected: !handedOff && !escalated,
    })
    .onConflictDoNothing()
    .run();
  return true;
}
